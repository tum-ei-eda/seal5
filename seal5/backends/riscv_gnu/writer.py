"""Generate a unified binutils/GDB patch from transformed Seal5 models."""

import argparse
import difflib
import json
import re
from functools import partial
from pathlib import Path

from seal5.model import Seal5RegOperand, Seal5RegisterClass
from seal5.model_utils import load_model
from .encoding import compile_encoding


HEADER = r"""/* Generated by Seal5.  Shared by GAS and libopcodes.  */
#ifndef RISCV_SEAL5_H
#define RISCV_SEAL5_H
struct seal5_slice { unsigned int dst, src, width; };
struct seal5_operand {
  unsigned int kind, width, is_signed, count;
  insn_t source_mask, instruction_mask;
  const struct seal5_slice *slices;
};
@DATA@
static inline const struct seal5_operand *
seal5_operand_arg (const char **arg)
{
  const char *p = *arg + 6;
  unsigned int id = 0;
  while (*p >= '0' && *p <= '9') id = id * 10 + *p++ - '0';
  *arg = p;
  return &seal5_operands[id];
}
static inline insn_t
seal5_extract (insn_t word, const struct seal5_operand *op)
{
  insn_t value = 0;
  unsigned int i;
  for (i = 0; i < op->count; ++i) {
    const struct seal5_slice *s = &op->slices[i];
    value |= ((word >> s->dst) & (~(insn_t)0 >> (64 - s->width))) << s->src;
  }
  return value;
}
static inline insn_t
seal5_insert (insn_t value, const struct seal5_operand *op)
{
  insn_t word = 0;
  unsigned int i;
  for (i = 0; i < op->count; ++i) {
    const struct seal5_slice *s = &op->slices[i];
    word |= ((value >> s->src) & (~(insn_t)0 >> (64 - s->width))) << s->dst;
  }
  return word;
}
static inline int
seal5_valid (insn_t value, const struct seal5_operand *op)
{
  insn_t mask = ~(insn_t)0 >> (64 - op->width);
  insn_t truncated = value & mask;
  insn_t extended = truncated;
  if (op->is_signed && (truncated & ((insn_t)1 << (op->width - 1))))
    extended |= ~mask;
  return extended == value && !(truncated & ~op->source_mask);
}
#endif
"""


def replace_once(text, anchor, replacement):
    """Fail on unrecognized upstream layouts instead of emitting a partial patch."""
    if text.count(anchor) != 1:
        raise ValueError(f"Expected one source anchor: {anchor!r}")
    return text.replace(anchor, replacement, 1)


def matching_delimiter(text, start, opening, closing):
    """Return the matching closing delimiter, ignoring comments and quoted text."""
    depth = 0
    quote = None
    line_comment = False
    block_comment = False
    index = start
    while index < len(text):
        char = text[index]
        next_char = text[index + 1] if index + 1 < len(text) else ""
        if line_comment:
            if char == "\n":
                line_comment = False
        elif block_comment:
            if char == "*" and next_char == "/":
                block_comment = False
                index += 1
        elif quote:
            if char == "\\":
                index += 1
            elif char == quote:
                quote = None
        elif char == "/" and next_char == "/":
            line_comment = True
            index += 1
        elif char == "/" and next_char == "*":
            block_comment = True
            index += 1
        elif char in ("'", '"'):
            quote = char
        elif char == opening:
            depth += 1
        elif char == closing:
            depth -= 1
            if depth == 0:
                return index
        index += 1
    raise ValueError(f"Unmatched {opening!r} in source")


def function_body(text, function):
    """Locate the unique definition body for a function name."""
    name = function.split("(", 1)[0].strip()
    if not re.fullmatch(r"[A-Za-z_]\w*", name):
        raise ValueError(f"Unsupported function name: {function!r}")
    definitions = []
    for match in re.finditer(r"\b" + re.escape(name) + r"\s*\(", text):
        opening = text.index("(", match.start(), match.end())
        closing = matching_delimiter(text, opening, "(", ")")
        brace = closing + 1
        while brace < len(text) and text[brace].isspace():
            brace += 1
        if brace < len(text) and text[brace] == "{":
            end = matching_delimiter(text, brace, "{", "}") + 1
            definitions.append((brace, end))
    if len(definitions) != 1:
        raise ValueError(f"Expected one definition of {name}, found {len(definitions)}")
    return definitions[0]


def insert_switch(text, function, content):
    """Insert content immediately before a function's unique operand switch."""
    start, end = function_body(text, function)
    body = text[start:end]
    if body.count("switch (*oparg)") != 1:
        raise ValueError(f"Expected one switch in {function.strip()}")
    pos = start + body.index("switch (*oparg)")
    content = re.sub(r"^(?: {8})+", lambda match: "\t" * (len(match.group()) // 8), content, flags=re.MULTILINE)
    return text[:pos] + content + "\n      " + text[pos:]


def substitute_assembly_operand(match, replacements, name):
    """Replace one assembly operand placeholder or reject an unknown name."""
    key = match.group(1)
    if key not in replacements:
        raise ValueError(f"Unsupported assembly operand {key} in {name}")
    return replacements[key]


def collect(models):
    """Collect deterministic tables, preserving arbitrary operand bit slices."""
    descriptors = []
    opcodes = []
    extensions = {}
    manifest = []
    seen = set()
    for model in models:
        for set_name, instruction_set in sorted(model.sets.items()):
            settings = instruction_set.settings
            if settings is None:
                continue
            arch = settings.get_arch(name=set_name)
            if not re.fullmatch(r"x[a-z][a-z0-9]*", arch):
                raise ValueError(f"GNU backend requires a vendor extension name: {arch}")
            version = settings.get_version()
            if not re.fullmatch(r"\d+\.\d+", version):
                raise ValueError(f"Unsupported extension version: {version}")
            if arch in extensions and extensions[arch] != version:
                raise ValueError(f"Conflicting versions for {arch}")
            extensions[arch] = version
            for instruction in sorted(instruction_set.instructions.values(), key=lambda item: item.mnemonic):
                name = instruction.mnemonic
                if not re.fullmatch(r"[a-zA-Z_][a-zA-Z0-9_.]*", name) or name in seen:
                    raise ValueError(f"Invalid or duplicate mnemonic: {name}")
                seen.add(name)
                encoding = compile_encoding(instruction)
                # GNU determines instruction length from the fixed low bits.
                low_mask = (
                    0x3
                    if encoding.size == 16
                    else 0x1F if encoding.size == 32 else 0x3F if encoding.size == 48 else 0x7F
                )
                low_value = encoding.match & low_mask
                valid = (
                    low_value != 3
                    if encoding.size == 16
                    else (
                        low_value & 3 == 3 and low_value != 31
                        if encoding.size == 32
                        else low_value == 31 if encoding.size == 48 else low_value == 63
                    )
                )
                if encoding.mask & low_mask != low_mask or not valid:
                    raise ValueError(f"GNU cannot determine instruction length for {name}")
                replacements = {}
                for operand_name, parts in encoding.operands.items():
                    operand = instruction.operands[operand_name]
                    kind = 0
                    if isinstance(operand, Seal5RegOperand):
                        kinds = {
                            Seal5RegisterClass.GPR: 1,
                            Seal5RegisterClass.FPR: 2,
                            Seal5RegisterClass.GPRC: 3,
                            Seal5RegisterClass.CSR: 4,
                        }
                        if operand.reg_class not in kinds:
                            raise ValueError(f"Unsupported register class for {name}.{operand_name}")
                        kind = kinds[operand.reg_class]
                    width = operand.ty.width
                    expected_width = {1: 5, 2: 5, 3: 3, 4: 12}.get(kind)
                    if kind and width != expected_width:
                        raise ValueError(
                            f"Register operand must encode a {expected_width}-bit index: {name}.{operand_name}"
                        )
                    if not width or width > 64 or max(p.operand_bit + p.width for p in parts) > width:
                        raise ValueError(f"Invalid operand width for {name}.{operand_name}")
                    source_mask = sum(((1 << p.width) - 1) << p.operand_bit for p in parts)
                    instruction_mask = sum(((1 << p.width) - 1) << p.instruction_bit for p in parts)
                    index = len(descriptors)
                    descriptors.append(
                        (kind, width, int(not kind and operand.ty.is_signed_int), parts, source_mask, instruction_mask)
                    )
                    replacements[operand_name] = f"Xseal5{index}_"
                assembly = instruction.get_asm_str()
                assembly = re.sub(r"name\(([^()]+)\)", r"\1", assembly)
                for op_name, operand in instruction.operands.items():
                    if isinstance(operand, Seal5RegOperand) and operand.reg_class == Seal5RegisterClass.GPRC:
                        assembly = assembly.replace("{8+" + op_name + "}", "{" + op_name + "}")
                        assembly = assembly.replace("{" + op_name + "+8}", "{" + op_name + "}")

                assembly = re.sub(
                    r"\{(\w+)\}",
                    partial(substitute_assembly_operand, replacements=replacements, name=name),
                    assembly,
                )
                assembly = re.sub(r"\s+", "", assembly)
                if not re.fullmatch(r"(?:Xseal5\d+_|[,()]|\s)*", assembly):
                    raise ValueError(f"Unsupported assembly syntax for {name}: {assembly}")
                if set(re.findall(r"Xseal5\d+_", assembly)) != set(replacements.values()):
                    raise ValueError(f"Assembly does not use all encoding operands for {name}")
                opcodes.append(
                    f'{{"{name}", {instruction_set.xlen}, INSN_CLASS_SEAL5_{arch.upper()}, '
                    f'"{assembly}", 0x{encoding.match:x}ULL, 0x{encoding.mask:x}ULL, match_opcode, 0 }},'
                )
                manifest.append(
                    {
                        "mnemonic": name,
                        "extension": arch,
                        "size": encoding.size,
                        "match": encoding.match,
                        "mask": encoding.mask,
                    }
                )
    if not opcodes:
        raise ValueError("No custom instructions found")
    data = []
    for index, (_, _, _, parts, _, _) in enumerate(descriptors):
        slices = ", ".join(f"{{{p.instruction_bit}, {p.operand_bit}, {p.width}}}" for p in parts)
        data.append(f"static const struct seal5_slice seal5_slices_{index}[] = {{{slices}}};")
    data.append("static const struct seal5_operand seal5_operands[] = {")
    for index, (kind, width, signed, parts, source, destination) in enumerate(descriptors):
        data.append(
            f"  {{{kind}, {width}, {signed}, {len(parts)}, 0x{source:x}ULL, "
            f"0x{destination:x}ULL, seal5_slices_{index}}},"
        )
    data.append("};")
    return HEADER.replace("@DATA@", "\n".join(data)), opcodes, extensions, manifest


def generate_patch(models, source):
    """Return a patch for one binutils-gdb checkout without changing that checkout."""
    source = Path(source)
    header, opcodes, extensions, manifest = collect(models)
    changed = {"include/opcode/riscv-seal5.h": ("", header)}
    paths = [
        "include/opcode/riscv.h",
        "opcodes/riscv-opc.c",
        "opcodes/riscv-dis.c",
        "gas/config/tc-riscv.c",
        "bfd/elfxx-riscv.c",
    ]
    original = {path: (source / path).read_text() for path in paths}
    if any("Xseal5" in text or "INSN_CLASS_SEAL5_" in text for text in original.values()):
        raise ValueError("Source already contains a Seal5 patch; generate against an unpatched checkout")
    enum = original[paths[0]]
    enum = replace_once(
        enum,
        "  INSN_CLASS_I,",
        "".join(f"  INSN_CLASS_SEAL5_{arch.upper()},\n" for arch in sorted(extensions)) + "  INSN_CLASS_I,",
    )
    changed[paths[0]] = (original[paths[0]], enum)
    table = original[paths[1]]
    table = replace_once(
        table,
        "const struct riscv_opcode riscv_opcodes[] =\n{",
        "const struct riscv_opcode riscv_opcodes[] =\n{\n" + "\n".join(opcodes),
    )
    changed[paths[1]] = (original[paths[1]], table)
    dis = original[paths[2]]
    styled = "fprintf_styled_ftype print" in dis
    style = "dis_style_text, " if styled else ""
    dis_hook = """if (strncmp (oparg, "Xseal5", 6) == 0)
        {
          const struct seal5_operand *op = seal5_operand_arg (&oparg);
          insn_t value = seal5_extract (l, op);
          if (op->kind && op->kind != 4)
            print (info->stream, @STYLE@"%s", op->kind == 2
                   ? riscv_fpr_names[value] : riscv_gpr_names[value + (op->kind == 3 ? 8 : 0)]);
          else {
            if (op->is_signed && (value & ((insn_t)1 << (op->width - 1))))
              value |= ~((insn_t)0) << (op->width - 1);
            if (op->is_signed)
              print (info->stream, @STYLE@"%lld", (long long)value);
            else
              print (info->stream, @STYLE@"%llu", (unsigned long long)value);
          }
          continue;
        }""".replace(
        "@STYLE@", style
    )
    if "pd->riscv_gpr_names" in dis:
        dis_hook = dis_hook.replace("riscv_gpr_names[", "pd->riscv_gpr_names[").replace(
            "riscv_fpr_names[value]", "pd->riscv_fpr_names[value]"
        )
    dis = insert_switch(dis, "print_insn_args (", dis_hook)
    dis = replace_once(dis, '#include "opcode/riscv.h"', '#include "opcode/riscv.h"\n#include "opcode/riscv-seal5.h"')
    changed[paths[2]] = (original[paths[2]], dis)
    gas = original[paths[3]]
    gas = insert_switch(
        gas,
        "validate_riscv_insn (",
        """if (strncmp (oparg, "Xseal5", 6) == 0)
        {
          const struct seal5_operand *op = seal5_operand_arg (&oparg);
          used_bits |= op->instruction_mask;
          continue;
        }""",
    )
    expression = (
        "my_getExpression (imm_expr, asarg, force_reloc);"
        if "bool *force_reloc" in gas
        else "my_getExpression (imm_expr, asarg);"
    )
    # Newer GNU passes force_reloc as a value rather than a pointer.
    if "my_getExpression (imm_expr, asarg, force_reloc)" in gas:
        expression = "my_getExpression (imm_expr, asarg, force_reloc);"
    gas = insert_switch(
        gas,
        "riscv_ip (",
        """if (strncmp (oparg, "Xseal5", 6) == 0)
            {
              const struct seal5_operand *op = seal5_operand_arg (&oparg);
              insn_t value;
              if (op->kind && op->kind != 4) {
                if (!reg_lookup (&asarg, op->kind == 2 ? RCLASS_FPR : RCLASS_GPR, &regno))
                  break;
                if (op->kind == 3 && (regno < 8 || regno > 15)) break;
                value = regno - (op->kind == 3 ? 8 : 0);
              } else if (op->kind == 4 && reg_lookup (&asarg, RCLASS_CSR, &regno)) {
                value = regno;
              } else {
                @EXPRESSION@
                if (imm_expr->X_op != O_constant) break;
                value = imm_expr->X_add_number;
                asarg = @EXPR_END@;
                imm_expr->X_op = O_absent;
              }
              if (!seal5_valid (value, op)) break;
              ip->insn_opcode |= seal5_insert (value, op);
              continue;
            }""".replace(
            "@EXPRESSION@", expression
        ).replace(
            "@EXPR_END@", "expr_parse_end" if "expr_parse_end" in gas else "expr_end"
        ),
    )
    gas = replace_once(gas, '#include "opcode/riscv.h"', '#include "opcode/riscv.h"\n#include "opcode/riscv-seal5.h"')
    changed[paths[3]] = (original[paths[3]], gas)
    bfd = original[paths[4]]
    for function, returned in [("riscv_multi_subset_supports (", False), ("riscv_multi_subset_supports_ext (", True)]:
        name = function.split("(", 1)[0].strip()
        if not re.search(r"\b" + re.escape(name) + r"\s*\(", bfd):
            if not returned:
                raise ValueError(f"Expected one source anchor: {function!r}")
            continue
        start, end = function_body(bfd, function)
        body = bfd[start:end]
        if body.count("    case INSN_CLASS_I:") != 1:
            raise ValueError(f"Expected one INSN_CLASS_I case in {name}")
        pos = start + body.index("    case INSN_CLASS_I:")
        cases = ""
        for arch in sorted(extensions):
            result = f'"{arch}"' if returned else f'riscv_subset_supports (rps, "{arch}")'
            cases += f"    case INSN_CLASS_SEAL5_{arch.upper()}:\n      return {result};\n"
        bfd = bfd[:pos] + cases + bfd[pos:]
    vendor_table = re.search(
        r"(static (?:const )?struct riscv_supported_ext riscv_supported_vendor_x_ext\[\] =\n\{)", bfd
    )
    anchor = (
        vendor_table.group(1) if vendor_table else "static struct riscv_supported_ext riscv_supported_std_ext[] =\n{"
    )
    entries = []
    for arch, version in sorted(extensions.items()):
        if re.search(r'\{"' + re.escape(arch) + r'"', bfd):
            raise ValueError(f"Extension already present in GNU sources: {arch}")
        major, minor = version.split(".")
        entries.append(f'  {{"{arch}", ISA_SPEC_CLASS_DRAFT, {major}, {minor}, 0 }},')
    bfd = replace_once(bfd, anchor, anchor + "\n" + "\n".join(entries))
    changed[paths[4]] = (original[paths[4]], bfd)
    patch = []
    for path, (before, after) in sorted(changed.items()):
        patch.extend(
            difflib.unified_diff(
                before.splitlines(True),
                after.splitlines(True),
                fromfile=f"a/{path}" if before else "/dev/null",
                tofile=f"b/{path}",
            )
        )
    return "".join(patch), manifest


def main():
    """Standalone backend entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("models", nargs="+", type=Path, help="Transformed .seal5model files")
    parser.add_argument("--source", required=True, type=Path, help="Unpatched binutils-gdb checkout")
    parser.add_argument("--output", "-o", required=True, type=Path, help="Unified patch output")
    args = parser.parse_args()
    patch, manifest = generate_patch([load_model(path) for path in args.models], args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(patch)
    args.output.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
